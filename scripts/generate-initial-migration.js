const fs = require("fs");
const path = require("path");
const { execSync } = require("child_process");

const schemaPath = path.join(__dirname, "..", "prisma", "schema.prisma");
let schema = fs.readFileSync(schemaPath, "utf8");

// Ensure postgresql provider with directUrl for Supabase
const pgSchema = schema.replace(
  /datasource\s+db\s+\{\s*provider\s*=\s*"[^"]+"\s*url\s*=\s*env\("DATABASE_URL"\)(?:\s*directUrl\s*=\s*env\("DIRECT_URL"\))?\s*\}/m,
  `datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DIRECT_URL")\n}`
);

const tempSchemaPath = path.join(__dirname, "..", "prisma", "schema.pg.prisma");
fs.writeFileSync(tempSchemaPath, pgSchema, "utf8");

try {
  console.log("Generating PostgreSQL migration SQL using prisma migrate diff...");
  const migrationSql = execSync(
    `npx prisma migrate diff --from-empty --to-schema-datamodel prisma/schema.pg.prisma --script`,
    {
      encoding: "utf8",
      env: {
        ...process.env,
        DATABASE_URL: "postgresql://postgres:postgres@localhost:5432/postgres",
        DIRECT_URL: "postgresql://postgres:postgres@localhost:5432/postgres",
      },
    }
  );

  const migrationDir = path.join(__dirname, "..", "prisma", "migrations", "20261024000000_init");
  if (!fs.existsSync(migrationDir)) {
    fs.mkdirSync(migrationDir, { recursive: true });
  }

  const migrationFilePath = path.join(migrationDir, "migration.sql");
  fs.writeFileSync(migrationFilePath, migrationSql, "utf8");
  console.log("Successfully created initial migration at:", migrationFilePath);
  console.log("Migration SQL preview:\n" + migrationSql.substring(0, 500) + "\n...");

  // Also create migration_lock.toml if needed by Prisma Migrate
  const lockFilePath = path.join(__dirname, "..", "prisma", "migrations", "migration_lock.toml");
  fs.writeFileSync(
    lockFilePath,
    '# Please do not edit this file manually\nprovider = "postgresql"\n',
    "utf8"
  );
  console.log("Successfully created migration_lock.toml with provider = postgresql");
} catch (err) {
  console.error("Failed to generate migration:", err);
} finally {
  if (fs.existsSync(tempSchemaPath)) {
    fs.unlinkSync(tempSchemaPath);
  }
}
